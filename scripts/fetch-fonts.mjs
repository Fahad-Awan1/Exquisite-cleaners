// Downloads the site's Google Fonts (Latin + Latin-extended only) into public/fonts/ and writes
// src/css/fonts.css, so the fonts are served from the site itself instead of Google's servers.
// All three families are SIL Open Font License, which allows self-hosting.
// Run with: node scripts/fetch-fonts.mjs
import fs from 'node:fs';

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,500;0,600;0,700;1,500;1,600&family=Great+Vibes&family=Montserrat:wght@400;500;600&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const KEEP = ['latin', 'latin-ext'];

const get = async (url, type) => {
  for (let i = 0; i < 5; i++) {
    try {
      const r = await fetch(url, { headers: { 'User-Agent': UA } });
      if (r.ok) return type === 'text' ? r.text() : Buffer.from(await r.arrayBuffer());
    } catch (e) { /* connection dropped: retry */ }
    await new Promise((res) => setTimeout(res, 1500));
  }
  throw new Error(`Could not download ${url}`);
};

const css = await get(CSS_URL, 'text');
const blocks = [...css.matchAll(/\/\* ([a-z-]+) \*\/\s*(@font-face \{[^}]+\})/g)].filter(([, subset]) => KEEP.includes(subset));
fs.mkdirSync('public/fonts', { recursive: true });
const saved = new Map(); // remote url -> local file (variable fonts share one file across weights)
let out = '/* Self-hosted fonts (SIL Open Font License). Generated by scripts/fetch-fonts.mjs */\n';
for (const [, subset, block] of blocks) {
  const family = block.match(/font-family: '([^']+)'/)[1];
  const style = block.match(/font-style: (\w+)/)[1];
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
  if (!saved.has(url)) {
    const name = `${family.toLowerCase().replace(/\s+/g, '-')}-${style}-${subset}-${saved.size + 1}.woff2`;
    fs.writeFileSync(`public/fonts/${name}`, await get(url));
    saved.set(url, name);
  }
  out += `/* ${subset} */\n${block.replace(url, `/fonts/${saved.get(url)}`)}\n`;
}
fs.writeFileSync('src/css/fonts.css', out);
console.log(`${blocks.length} @font-face rules, ${saved.size} font files saved to public/fonts/`);
